use gitcko_domain::RepoPath;

/// A file's language, from its extension or name. Only languages with a parser adapter
/// get symbols and a graph; the rest are searched as text (IX-003).
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, serde::Serialize, serde::Deserialize,
)]
#[serde(rename_all = "snake_case")]
pub enum Language {
    Rust,
    TypeScript,
    Tsx,
    JavaScript,
    Python,
    Go,
    Java,
    C,
    Cpp,
    CSharp,
    Ruby,
    Php,
    Kotlin,
    Swift,
    Shell,
    Sql,
    Html,
    Css,
    Markdown,
    Toml,
    Yaml,
    Json,
}

/// A file's job in the repository, separate from its language (INDEXING §9.2): a
/// TypeScript file can be source or a test, YAML can be configuration or a workflow.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, serde::Serialize, serde::Deserialize,
)]
#[serde(rename_all = "snake_case")]
pub enum FileRole {
    Source,
    Test,
    Configuration,
    Manifest,
    DependencyLock,
    Migration,
    Template,
    Documentation,
    Generated,
    Vendor,
    BuildDefinition,
    Workflow,
    Unknown,
}

/// Everything [`classify`] decided about one file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Classification {
    pub language: Option<Language>,
    pub role: FileRole,
    /// A NUL byte in the first 8000 bytes, git's own test.
    pub binary: bool,
    /// A generated-code marker near the top, or a generated-file name.
    pub generated: bool,
    /// Under a `vendor/`, `third_party/` or `node_modules/` folder.
    pub vendor: bool,
    /// A Git LFS pointer: the real content isn't in the repository.
    pub lfs_pointer: bool,
}

impl Language {
    /// Whether Gitcko can parse this language into symbols and edges. Rust is the first
    /// adapter (RM-2); the other MVP languages come in Phase 6.
    pub fn has_adapter(self) -> bool {
        matches!(self, Language::Rust)
    }
}

/// Classifies the file at `path` from its name and `head`, its first bytes (the whole
/// file is fine; only the start is read).
pub fn classify(path: &RepoPath, head: &[u8]) -> Classification {
    let path = path.as_str();
    let parts: Vec<&str> = path.split('/').collect();
    let name = parts.last().copied().unwrap_or_default();
    let language = language(name);
    let vendor = parts[..parts.len() - 1]
        .iter()
        .any(|p| VENDOR_FOLDERS.contains(p));
    let generated = has_generated_marker(head) || is_generated_name(name);
    Classification {
        language,
        role: role(path, &parts, name, language, generated, vendor),
        binary: head.iter().take(BINARY_SNIFF).any(|b| *b == 0),
        generated,
        vendor,
        lfs_pointer: head.starts_with(LFS_POINTER),
    }
}

/// How far git looks for a NUL byte when deciding a file is binary (`FIRST_FEW_BYTES` in
/// git's `xdiff-interface.c`). Using git's rule keeps us in step with what `git diff`
/// treats as binary.
const BINARY_SNIFF: usize = 8000;

/// How far down a generated-code marker still counts as a header.
const MARKER_SNIFF: usize = 2048;

/// The first line of every Git LFS pointer file (git-lfs spec v1).
const LFS_POINTER: &[u8] = b"version https://git-lfs.github.com/spec/v1\n";

const VENDOR_FOLDERS: &[&str] = &["vendor", "third_party", "third-party", "node_modules"];

/// Markers tools write at the top of generated files: Facebook's `@generated`, Go's
/// "Code generated … DO NOT EDIT." convention, .NET's `<auto-generated>`.
const GENERATED_MARKERS: &[&[u8]] = &[b"@generated", b"DO NOT EDIT", b"<auto-generated"];

fn has_generated_marker(head: &[u8]) -> bool {
    let head = &head[..head.len().min(MARKER_SNIFF)];
    GENERATED_MARKERS
        .iter()
        .any(|m| head.windows(m.len()).any(|w| w == *m))
}

fn is_generated_name(name: &str) -> bool {
    let name = name.to_ascii_lowercase();
    [".min.js", ".min.css", ".pb.go", "_pb2.py"]
        .iter()
        .any(|end| name.ends_with(end))
        || name.contains(".generated.")
}

/// The extension after the last dot, lowercased; none for dot files like `.rs`.
fn extension(name: &str) -> Option<String> {
    match name.rsplit_once('.') {
        Some((stem, ext)) if !stem.is_empty() => Some(ext.to_ascii_lowercase()),
        _ => None,
    }
}

fn language(name: &str) -> Option<Language> {
    use Language::*;
    Some(match extension(name)?.as_str() {
        "rs" => Rust,
        "ts" | "mts" | "cts" => TypeScript,
        "tsx" => Tsx,
        "js" | "mjs" | "cjs" | "jsx" => JavaScript,
        "py" | "pyi" => Python,
        "go" => Go,
        "java" => Java,
        "c" | "h" => C,
        "cc" | "cpp" | "cxx" | "hpp" | "hh" => Cpp,
        "cs" => CSharp,
        "rb" => Ruby,
        "php" => Php,
        "kt" | "kts" => Kotlin,
        "swift" => Swift,
        "sh" | "bash" | "zsh" => Shell,
        "sql" => Sql,
        "html" | "htm" => Html,
        "css" | "scss" => Css,
        "md" | "markdown" => Markdown,
        "toml" => Toml,
        "yml" | "yaml" => Yaml,
        "json" => Json,
        _ => return None,
    })
}

const MANIFESTS: &[&str] = &[
    "Cargo.toml",
    "package.json",
    "go.mod",
    "pyproject.toml",
    "setup.py",
    "requirements.txt",
    "pom.xml",
    "build.gradle",
    "build.gradle.kts",
    "Gemfile",
    "composer.json",
];

const LOCKFILES: &[&str] = &[
    "Cargo.lock",
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "go.sum",
    "poetry.lock",
    "Pipfile.lock",
    "Gemfile.lock",
    "composer.lock",
];

const BUILD_FILES: &[&str] = &[
    "build.rs",
    "Makefile",
    "CMakeLists.txt",
    "Dockerfile",
    "BUILD",
    "BUILD.bazel",
    "Justfile",
];

/// The most specific role wins: vendored and generated code first (whatever language
/// it's in), then files named by convention, then folder conventions, then by type.
fn role(
    path: &str,
    parts: &[&str],
    name: &str,
    language: Option<Language>,
    generated: bool,
    vendor: bool,
) -> FileRole {
    let folders = &parts[..parts.len() - 1];
    let in_folder = |names: &[&str]| folders.iter().any(|f| names.contains(f));
    let ext = extension(name);
    if vendor {
        FileRole::Vendor
    } else if generated {
        FileRole::Generated
    } else if LOCKFILES.contains(&name) {
        FileRole::DependencyLock
    } else if MANIFESTS.contains(&name) {
        FileRole::Manifest
    } else if path.starts_with(".github/workflows/") || name == ".gitlab-ci.yml" {
        FileRole::Workflow
    } else if BUILD_FILES.contains(&name) {
        FileRole::BuildDefinition
    } else if in_folder(&["migrations"]) {
        FileRole::Migration
    } else if is_test(path, folders, name) {
        FileRole::Test
    } else if in_folder(&["templates"]) {
        FileRole::Template
    } else if matches!(language, Some(Language::Markdown))
        || matches!(ext.as_deref(), Some("rst" | "adoc" | "txt"))
        || in_folder(&["docs", "doc"])
    {
        FileRole::Documentation
    } else if matches!(
        language,
        Some(Language::Toml | Language::Yaml | Language::Json)
    ) || matches!(ext.as_deref(), Some("ini" | "cfg" | "conf" | "xml"))
    {
        FileRole::Configuration
    } else if language.is_some() {
        FileRole::Source
    } else {
        FileRole::Unknown
    }
}

/// Test-file conventions of the common ecosystems: a `tests`/`__tests__` folder,
/// Maven's `src/test/`, Go's `_test.go`, pytest's `test_*.py`/`*_test.py`, and the JS
/// `.test.`/`.spec.` infix. Case-sensitive, as the tools that define them are.
fn is_test(path: &str, folders: &[&str], name: &str) -> bool {
    folders.iter().any(|f| *f == "tests" || *f == "__tests__")
        || path.contains("src/test/")
        || name.ends_with("_test.go")
        || (name.ends_with(".py") && (name.starts_with("test_") || name.ends_with("_test.py")))
        || name.contains(".test.")
        || name.contains(".spec.")
}
