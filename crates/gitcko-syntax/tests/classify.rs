use gitcko_domain::RepoPath;
use gitcko_syntax::{FileRole, Language, classify};

fn class(path: &str, head: &[u8]) -> gitcko_syntax::Classification {
    classify(&RepoPath::parse(path).unwrap(), head)
}

#[test]
fn languages_come_from_extensions_and_well_known_names() {
    use Language::*;
    for (path, language) in [
        ("src/main.rs", Some(Rust)),
        ("web/app.ts", Some(TypeScript)),
        ("web/app.tsx", Some(Tsx)),
        ("web/app.mjs", Some(JavaScript)),
        ("web/app.jsx", Some(JavaScript)),
        ("tool.py", Some(Python)),
        ("cmd/main.go", Some(Go)),
        ("App.java", Some(Java)),
        ("run.sh", Some(Shell)),
        ("README.md", Some(Markdown)),
        ("Cargo.toml", Some(Toml)),
        ("ci.yml", Some(Yaml)),
        ("data.json", Some(Json)),
        // Extensions are matched case-insensitively: Windows and macOS users write them
        // in any case.
        ("LEGACY.RS", Some(Rust)),
        ("LICENSE", None),
        ("archive.tar.gz", None),
        // A dot file has no extension.
        (".rs", None),
    ] {
        assert_eq!(class(path, b"").language, language, "{path}");
    }
}

#[test]
fn only_rust_has_a_parser_adapter_so_far() {
    assert!(Language::Rust.has_adapter());
    for other in [Language::TypeScript, Language::Python, Language::Markdown] {
        assert!(!other.has_adapter(), "{other:?}");
    }
}

#[test]
fn roles_follow_paths_and_names() {
    use FileRole::*;
    for (path, role) in [
        ("src/lib.rs", Source),
        ("tests/api.rs", Test),
        ("crates/a/tests/api.rs", Test),
        ("pkg/server_test.go", Test),
        ("tests/test_api.py", Test),
        ("app/test_api.py", Test),
        ("web/app.test.ts", Test),
        ("web/app.spec.tsx", Test),
        ("web/__tests__/app.js", Test),
        ("src/test/java/AppTest.java", Test),
        ("Cargo.toml", Manifest),
        ("package.json", Manifest),
        ("go.mod", Manifest),
        ("Cargo.lock", DependencyLock),
        ("web/package-lock.json", DependencyLock),
        ("go.sum", DependencyLock),
        ("db/migrations/001_init.sql", Migration),
        ("templates/page.html", Template),
        ("docs/guide.md", Documentation),
        ("README.md", Documentation),
        ("config/app.yaml", Configuration),
        (".gitcko/config.toml", Configuration),
        ("build.rs", BuildDefinition),
        ("Makefile", BuildDefinition),
        ("Dockerfile", BuildDefinition),
        (".github/workflows/ci.yml", Workflow),
        (".gitlab-ci.yml", Workflow),
        ("vendor/lib/a.rs", Vendor),
        ("web/node_modules/x/index.js", Vendor),
        ("LICENSE", Unknown),
        // GitHub only runs workflows from `.github/workflows/`, spelled exactly so.
        (".GITHUB/workflows/ci.yml", Configuration),
    ] {
        assert_eq!(class(path, b"").role, role, "{path}");
    }
}

#[test]
fn a_tests_folder_only_counts_as_a_whole_path_part() {
    // `contests/` and `tests.rs` aren't test folders.
    assert_eq!(class("src/contests/a.rs", b"").role, FileRole::Source);
    assert_eq!(class("src/tests.rs", b"").role, FileRole::Source);
    // `go test` only picks up a lowercase `_test.go` suffix.
    assert_eq!(class("pkg/server_TEST.go", b"").role, FileRole::Source);
}

#[test]
fn binary_means_a_nul_byte_in_the_first_8000_bytes_like_git() {
    let mut late = vec![b'a'; 8000];
    late.push(0);
    assert!(class("a.bin", b"\x89PNG\r\n\x1a\n\0\0").binary);
    assert!(
        !class("a.rs", &late).binary,
        "a NUL after byte 8000 isn't looked at"
    );
    late[7999] = 0;
    assert!(class("a.rs", &late).binary);
    assert!(!class("a.rs", "fn é() {}\r\n".as_bytes()).binary);
}

#[test]
fn generated_files_are_found_by_marker_or_name_and_flagged() {
    for (path, head) in [
        ("src/gen.rs", &b"// @generated by a tool\nfn a() {}"[..]),
        (
            "api/x.go",
            b"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x",
        ),
        ("a.cs", b"// <auto-generated>\n"),
        ("web/app.min.js", b"var a=1"),
        ("api/x.pb.go", b"package x"),
        ("api/x_pb2.py", b"import x"),
        ("web/schema.generated.ts", b"export {}"),
    ] {
        let c = class(path, head);
        assert!(c.generated, "{path}");
        assert_eq!(c.role, FileRole::Generated, "{path}");
    }
    // A marker far down the file isn't a header.
    let mut late = vec![b'\n'; 3000];
    late.extend(b"// @generated");
    assert!(!class("src/a.rs", &late).generated);
}

#[test]
fn vendor_wins_over_every_other_role_and_keeps_its_language() {
    let c = class(
        "vendor/github.com/x/x_test.go",
        b"// Code generated. DO NOT EDIT.",
    );
    assert!(c.vendor && c.generated);
    assert_eq!(c.role, FileRole::Vendor);
    assert_eq!(c.language, Some(Language::Go));
    assert!(!class("src/vendored.rs", b"").vendor);
}

#[test]
fn lfs_pointers_are_recognised_by_their_first_line() {
    let pointer = b"version https://git-lfs.github.com/spec/v1\noid sha256:4d7a\nsize 12345\n";
    assert!(class("assets/model.bin", pointer).lfs_pointer);
    assert!(!class("docs/lfs.md", b"see https://git-lfs.github.com/spec/v1").lfs_pointer);
}
